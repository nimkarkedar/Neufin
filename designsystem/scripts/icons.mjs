// Copies the Nucleo icons named in src/brand/icon-list.json from the local Nucleo
// install into src/brand/icons.generated.js (icons in use) and
// src/brand/icon-samples.generated.js (the family samples on the Iconography page),
// so the repo builds without a Nucleo licence. Only listed icons are copied; the
// full set is licensed and stays out of the repo.
//
// Needs Nucleo installed once: npx @nucleoicons/skills setup --target vanilla --tools claude
// Run: npm run icons

import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const root = process.env.NUCLEO_SKILLS_ROOT || join(homedir(), '.nucleo', 'skills');
const here = new URL('../src/brand/', import.meta.url);
const list = JSON.parse(readFileSync(new URL('icon-list.json', here), 'utf8'));

const catalogues = {};
function catalogue(family) {
  if (!catalogues[family]) {
    const data = JSON.parse(readFileSync(join(root, family, 'icons.json'), 'utf8'));
    catalogues[family] = Array.isArray(data) ? data : data.icons;
  }
  return catalogues[family];
}

// Families Neufin never uses. Keep in step with the Iconography page.
const notUsed = ['pixel', 'isometric', 'arcade'];

const missing = [];

// Returns { family, label, viewBox, body } for one icon, or null if not found.
function find({ family, label, fill, size }) {
  if (notUsed.includes(family)) throw new Error(`The ${family} family is not used by Neufin.`);
  const hit = catalogue(family).find(
    (i) => i.label === label && (!fill || i.fills?.includes(fill)) && (!size || i.sizes?.includes(size)),
  );
  if (!hit) {
    missing.push(`${family}/${label}${fill ? ` ${fill}` : ''}${size ? ` ${size}` : ''}`);
    return null;
  }
  const svg = readFileSync(join(root, family, 'icons', `${hit.id}.svg`), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  // Secondary parts follow --icon-color-2 when it is set, else the main colour.
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/(fill|stroke)="currentColor"([^>]*?)data-color="color-2"/g, '$1="var(--icon-color-2, currentColor)"$2data-color="color-2"')
    .replace(/\s+/g, ' ')
    .trim();
  return { family, label, fill: fill || null, size: size || null, viewBox, body };
}

const icons = Object.fromEntries(Object.entries(list.icons).map(([name, spec]) => [name, find(spec)]));
const samples = list.samples.map(({ labels, ...set }) => ({
  ...set,
  icons: labels.map((label) => find({ ...set, label })).filter(Boolean),
}));

if (missing.length) {
  console.error(`Not found in Nucleo:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const banner = '// Generated by scripts/icons.mjs from icon-list.json. Do not edit by hand.\n';
writeFileSync(new URL('icons.generated.js', here), `${banner}export const nucleoIcons = ${JSON.stringify(icons, null, 1)};\n`);
// Kept separate so the website, which imports icons.js, doesn't carry the samples.
writeFileSync(new URL('icon-samples.generated.js', here), `${banner}export const nucleoSamples = ${JSON.stringify(samples, null, 1)};\n`);
console.log(`Copied ${Object.keys(icons).length} icons and ${samples.reduce((n, s) => n + s.icons.length, 0)} samples.`);
